# -*- coding: utf-8 -*-
"""ЛР05 Р4: перенесення в підсумкову таксономію того, що знайшла LLM-чернетка.

Переносяться 23 терміни корпусу, яких експертна версія не охопила, і структурний
хід моделі — поділ облікових документів за функцією. Кожна зміна має джерело `llm`.
"""
import csv, pathlib

HUB = pathlib.Path(__file__).resolve().parents[1]
P = HUB / "models/taxonomy_final.csv"
rows = list(csv.DictReader(P.open(encoding="utf-8")))
FIELDS = list(rows[0].keys())
by_id = {r["id"]: r for r in rows}
by_label = {r["label"]: r for r in rows}

if "f154" in by_id:                       # крок уже застосовано
    print("перенесення з LLM-чернетки вже застосоване — нічого не роблю")
    raise SystemExit(0)

def node(nid, parent, label, level, definition="", alt="", dp="", source="llm"):
    return {"id": nid, "parent_id": parent, "label": label, "level": str(level),
            "definition": definition, "alt_labels": alt,
            "division_principle": dp, "source": source}

new = []

# --- 1. родові поняття оцінювання збереженості (LLM: «Узагальнені поняття…»)
by_id["e38"]["division_principle"] = (
    "за роллю поняття в оцінюванні збереженості: окремо родові поняття, "
    "далі чинники за фізичною природою впливу")
new += [
    node("f154", "e38", "Узагальнена оцінка збереженості", 2,
         "Родові поняття, що узагальнюють причину руйнування та результат її дії.",
         dp="за спрямованістю узагальнення: на причину впливу чи на його результат"),
    node("f155", "f154", "чинник руйнування", 3),
    node("f156", "f154", "стан збереженості", 3),
]

# --- 2. дії над записами знання (LLM: «Опрацювання термінів і записів…»)
by_id["e67"]["division_principle"] = (
    "за предметом дії: матеріальний об'єкт або відомості про нього")
new += [
    node("f157", "e67", "Опрацювання записів знання", 2,
         "Операції над сукупністю термінів і записів, що впорядковують та перевіряють модель.",
         dp="за операцією над множиною термінів або записів"),
    node("f158", "f157", "нормалізація термінів", 3),
    node("f159", "f157", "дедуплікація", 3),
    node("f160", "f157", "кластеризація", 3),
    node("f161", "f157", "верифікація", 3),
]

# --- 3. поодинокі терміни в наявні гілки
singles = [
    ("f162", "e68", "атрибуція"),
    ("f163", "e75", "профілактичне заклеювання"),
    ("f164", "e127", "канонічний термін"),
    ("f165", "e127", "front matter"),
    ("f166", "e137", "принцип поділу"),
    ("f167", "e137", "MECE"),
    ("f168", "e02", "монументальний живопис"),
    ("f169", "e09", "науково-допоміжний матеріал"),
]
new += [node(i, p, l, int(by_id[p]["level"]) + 1) for i, p, l in singles]

# --- 4. показники якості моделі (LLM: «Показники якості та узгодженості моделі»)
by_id["e112"]["division_principle"] = "за функцією запису в системі знань"
new += [
    node("f170", "e112", "Показник якості моделі", 2,
         "Числові величини, якими вимірюють повноту, перевіреність і узгодженість моделі.",
         dp="за властивістю моделі, яку вимірює показник"),
    node("f171", "f170", "покриття таксономії", 3),
    node("f172", "f170", "коефіцієнт згоди", 3),
    node("f173", "f170", "скоригований індекс Ренда", 3),
]
# «рівень верифікації» — метрика, а не ідентифікатор: переносимо з «Ідентифікації»
by_label["рівень верифікації"]["parent_id"] = "f170"
by_label["рівень верифікації"]["level"] = "3"
by_label["рівень верифікації"]["source"] = "llm"

# --- 5. поділ облікових документів за функцією (структурний хід LLM)
by_id["e113"]["division_principle"] = "за функцією документа в управлінні зібранням"
groups = {
    "f174": ("Документи фондового та памʼяткового обліку",
             "Документи, що реєструють склад зібрання та описові відомості про кожну одиницю.",
             "за видом облікових відомостей, які фіксує документ",
             ["книга надходжень", "інвентарна книга", "облікова картка музейного предмета",
              "топографічний опис", "паспорт нерухомої памʼятки"],
             ["облікова база даних"]),
    "f175": ("Правові документи руху та відповідальності",
             "Документи, якими юридично оформлюють перехід предметів та обов'язки щодо них.",
             "за юридичною дією, яку засвідчує документ",
             ["акт приймання-передавання", "акт вилучення", "охоронний договір"],
             ["книга реєстрації актів"]),
    "f176": ("Документи експертизи та реставраційного процесу",
             "Документи, що обґрунтовують, призначають і фіксують втручання у твір.",
             "за етапом втручання, який документ обслуговує",
             ["акт технічного стану", "експертний висновок", "реставраційний паспорт",
              "науково-проєктна документація"],
             ["реставраційне завдання"]),
    "f177": ("Журнали режимного контролю та документи готовності",
             "Регулярні записи про показники середовища, справність засобів і готовність персоналу.",
             "за об'єктом регулярного спостереження, який реєструє документ",
             ["план евакуації"],
             ["журнал температурно-вологісного режиму", "журнал калібрувань", "журнал навчань"]),
}
nxt = 178
for gid, (label, defn, dp, existing, added) in groups.items():
    new.append(node(gid, "e113", label, 3, defn, dp=dp))
    for lbl in existing:
        r = by_label[lbl]
        r["parent_id"], r["level"] = gid, "4"
    for lbl in added:
        new.append(node(f"f{nxt}", gid, lbl, 4))
        nxt += 1

# --- 6. родовий термін усієї області — друга назва кореня, а не окремий листок
by_id["e01"]["alt_labels"] = "; ".join(
    x for x in [by_id["e01"]["alt_labels"], "обʼєкт культурної спадщини"] if x)

rows += new
with P.open("w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=FIELDS)
    w.writeheader()
    w.writerows(rows)
print(f"додано вузлів: {len(new)}; усього: {len(rows)}")
